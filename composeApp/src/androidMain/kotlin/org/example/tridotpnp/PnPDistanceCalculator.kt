    var depthInitFallbackMm: Float = 1000f
    var solverMaxIterations: Int = 50
    var solverConvergenceErrorMm: Float = 0.1f
    var solverLearningRate: Float = 0.5f
    var solverMinDepthMm: Float = 100f

